import Foundation

enum AgentThemeWriter {
    static func writePi(
        _ palettes: TerminalPalettePair,
        _ wallpaperURL: URL,
        directory: URL? = nil
    ) throws -> [URL] {
        let root = directory ?? configDirectory(variable: "PI_CODING_AGENT_DIR", fallback: ".pi/agent")
        return try variants(palettes).map { name, palette in
            let colors = AgentColors(palette)
            let payload: [String: Any] = [
                "$schema": "https://raw.githubusercontent.com/earendil-works/pi/main/packages/coding-agent/src/modes/interactive/theme/theme-schema.json",
                "name": name,
                "colors": colors.piColors,
                "export": [
                    "pageBg": palette.background.hex,
                    "cardBg": colors.panel.hex,
                    "infoBg": colors.surface.hex
                ]
            ]
            let data = try JSONSerialization.data(withJSONObject: payload, options: [.prettyPrinted, .sortedKeys])
            let url = root.appendingPathComponent("themes/\(name).json")
            try write(data + Data("\n".utf8), to: url)
            return url
        }
    }

    static func writeCodexCLI(
        _ palettes: TerminalPalettePair,
        _ wallpaperURL: URL,
        directory: URL? = nil
    ) throws -> [URL] {
        let root = directory ?? configDirectory(variable: "CODEX_HOME", fallback: ".codex")
        return try variants(palettes).map { name, palette in
            let colors = AgentColors(palette)
            let payload: [String: Any] = [
                "name": name,
                "author": "MWall",
                "comment": "Generated by MWall\nWallpaper: \(wallpaperURL.path)",
                "settings": colors.textMateSettings
            ]
            // Use the plist serializer so wallpaper paths and names are XML-escaped correctly.
            let data = try PropertyListSerialization.data(fromPropertyList: payload, format: .xml, options: 0)
            let url = root.appendingPathComponent("themes/\(name).tmTheme")
            try write(data, to: url)
            return url
        }
    }

    static func configDirectory(
        variable: String,
        fallback: String,
        environment: [String: String] = ProcessInfo.processInfo.environment,
        homeDirectory: URL = FileManager.default.homeDirectoryForCurrentUser
    ) -> URL {
        guard let value = environment[variable], !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return homeDirectory.appendingPathComponent(fallback)
        }
        if value == "~" { return homeDirectory }
        if value.hasPrefix("~/") {
            return homeDirectory.appendingPathComponent(String(value.dropFirst(2)))
        }
        return URL(fileURLWithPath: value, isDirectory: true)
    }

    private static func variants(_ palettes: TerminalPalettePair) -> [(String, TerminalPalette)] {
        [("mwall-dark", palettes.dark), ("mwall-light", palettes.light), ("mwall", palettes.current)]
    }

    private static func write(_ data: Data, to url: URL) throws {
        // Identical palettes need not wake pi's live theme watcher.
        if (try? Data(contentsOf: url)) == data { return }
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try data.write(to: url, options: .atomic)
    }
}

private struct AgentColors {
    let palette: TerminalPalette
    let muted: RGBColor
    let dim: RGBColor
    let surface: RGBColor
    let panel: RGBColor
    let red: RGBColor
    let green: RGBColor
    let yellow: RGBColor
    let blue: RGBColor
    let magenta: RGBColor
    let cyan: RGBColor
    let added: RGBColor
    let removed: RGBColor

    init(_ palette: TerminalPalette) {
        self.palette = palette
        let isDark = palette.background.luminance < 0.5
        muted = palette.foreground.blended(with: palette.background, amount: isDark ? 0.45 : 0.40)
        dim = palette.foreground.blended(with: palette.background, amount: isDark ? 0.62 : 0.55)
        surface = palette.background.blended(with: palette.foreground, amount: isDark ? 0.08 : 0.05)
        panel = palette.background.blended(with: palette.foreground, amount: isDark ? 0.12 : 0.08)
        func normal(_ index: Int) -> RGBColor {
            palette.normal.indices.contains(index) ? palette.normal[index] : palette.cursor
        }
        red = normal(1)
        green = normal(2)
        yellow = normal(3)
        blue = normal(4)
        magenta = normal(5)
        cyan = normal(6)
        added = green.blended(with: palette.background, amount: isDark ? 0.88 : 0.94)
        removed = red.blended(with: palette.background, amount: isDark ? 0.88 : 0.94)
    }

    var piColors: [String: String] {
        [
            "accent": palette.cursor.hex,
            "border": blue.hex,
            "borderAccent": palette.cursor.hex,
            "borderMuted": dim.hex,
            "success": green.hex,
            "error": red.hex,
            "warning": yellow.hex,
            "muted": muted.hex,
            "dim": dim.hex,
            "text": palette.foreground.hex,
            "thinkingText": muted.hex,
            "selectedBg": palette.selectionBackground.hex,
            "scrollbarTrack": dim.hex,
            "scrollbarThumb": palette.cursor.hex,
            "searchMatchBg": palette.selectionBackground.hex,
            "searchMatchText": palette.selectionForeground.hex,
            "userMessageBg": panel.hex,
            "userMessageText": palette.foreground.hex,
            "customMessageBg": surface.hex,
            "customMessageText": palette.foreground.hex,
            "customMessageLabel": magenta.hex,
            "toolPendingBg": surface.hex,
            "toolSuccessBg": added.hex,
            "toolErrorBg": removed.hex,
            "toolTitle": palette.cursor.hex,
            "toolOutput": palette.foreground.hex,
            "mdHeading": palette.cursor.hex,
            "mdLink": blue.hex,
            "mdLinkUrl": muted.hex,
            "mdCode": cyan.hex,
            "mdCodeBlock": palette.foreground.hex,
            "mdCodeBlockBorder": dim.hex,
            "mdQuote": muted.hex,
            "mdQuoteBorder": dim.hex,
            "mdHr": dim.hex,
            "mdListBullet": cyan.hex,
            "toolDiffAdded": green.hex,
            "toolDiffRemoved": red.hex,
            "toolDiffContext": muted.hex,
            "syntaxComment": muted.hex,
            "syntaxKeyword": magenta.hex,
            "syntaxFunction": blue.hex,
            "syntaxVariable": palette.foreground.hex,
            "syntaxString": green.hex,
            "syntaxNumber": magenta.hex,
            "syntaxType": yellow.hex,
            "syntaxOperator": cyan.hex,
            "syntaxPunctuation": muted.hex,
            "thinkingOff": dim.hex,
            "thinkingMinimal": muted.hex,
            "thinkingLow": blue.hex,
            "thinkingMedium": cyan.hex,
            "thinkingHigh": magenta.hex,
            "thinkingXhigh": red.hex,
            "thinkingMax": palette.cursor.hex,
            "bashMode": yellow.hex
        ]
    }

    var textMateSettings: [[String: Any]] {
        func rule(_ name: String, _ scope: String, _ color: RGBColor, style: String = "") -> [String: Any] {
            ["name": name, "scope": scope, "settings": ["foreground": color.hex, "fontStyle": style]]
        }
        return [
            ["settings": [
                "background": palette.background.hex,
                "foreground": palette.foreground.hex,
                "caret": palette.cursor.hex,
                "selection": palette.selectionBackground.hex,
                "selectionForeground": palette.selectionForeground.hex,
                "lineHighlight": surface.hex,
                "gutter": palette.background.hex,
                "gutterForeground": muted.hex
            ]],
            rule("Comments", "comment", muted, style: "italic"),
            rule("Strings", "string", green),
            rule("Constants", "constant.numeric, constant.language, constant.character", magenta),
            rule("Keywords", "keyword, storage", magenta),
            rule("Functions", "entity.name.function, support.function", blue),
            rule("Types", "entity.name.type, entity.name.class, support.type, support.class", yellow),
            rule("Variables", "variable", palette.foreground),
            rule("Operators", "keyword.operator", cyan),
            rule("Punctuation", "punctuation", muted),
            rule("Headings", "markup.heading", palette.cursor, style: "bold"),
            rule("Links", "markup.underline.link, string.other.link", blue, style: "underline"),
            rule("Inline code", "markup.raw", cyan),
            rule("Added", "markup.inserted", green),
            rule("Removed", "markup.deleted", red),
            rule("Changed", "markup.changed", yellow),
            rule("Invalid", "invalid", red, style: "underline")
        ]
    }
}
